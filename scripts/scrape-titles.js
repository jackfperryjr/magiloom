// Scrape every DragonRealms title from Elanthipedia into a generated data file.
// Run: node scripts/scrape-titles.js   →  src/renderer/src/lib/drTitles.generated.ts
//
// WHY. A LOOK at someone with a chosen title reads "You see Paintress Catheroine
// Rotschreck, a Human." The portrait key is the character's first name, and the
// fallback paths that read the "You see" line need to know "Paintress" is a title,
// not a name. There are thousands of titles and new ones appear, so the list is
// copied mechanically rather than typed by hand.
//
// SOURCE. Category:Titles on elanthipedia.play.net, read via the MediaWiki API (no
// HTML scraping). Pages live in the Title: namespace (116); a disambiguating suffix
// like "Accountant (Trader)" is dropped because the game shows only "Accountant".
// The output is committed so the app never depends on the wiki at runtime — re-run
// this and diff when new titles ship.

const fs = require('fs')
const path = require('path')

const API = 'https://elanthipedia.play.net/api.php'
const OUT = path.resolve(__dirname, '..', 'src/renderer/src/lib/drTitles.generated.ts')

async function fetchAll() {
  const titles = []
  let cont = ''
  for (;;) {
    const q = new URLSearchParams({
      action: 'query', list: 'categorymembers', cmtitle: 'Category:Titles',
      cmnamespace: '116', cmlimit: '500', format: 'json',
    })
    if (cont) q.set('cmcontinue', cont)
    const res = await fetch(`${API}?${q}`, { headers: { 'User-Agent': 'lantern-title-scrape' } })
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const data = await res.json()
    for (const m of data.query.categorymembers) titles.push(m.title)
    cont = data.continue?.cmcontinue
    if (!cont) break
  }
  return titles
}

async function main() {
  const raw = await fetchAll()
  const names = [...new Set(raw
    .map(t => t.replace(/^Title:/, '').replace(/\s*\([^)]*\)\s*$/, '').trim())
    .filter(Boolean))]
    .sort((a, b) => a.localeCompare(b))
  if (names.length < 1000) throw new Error(`only ${names.length} titles — refusing to overwrite`)

  const body =
    `// GENERATED by scripts/scrape-titles.js — do not edit by hand.\n` +
    `// Source: ${API} (Category:Titles), ${raw.length} pages → ${names.length} titles.\n` +
    `// Scraped ${new Date().toISOString().slice(0, 10)}.\n\n` +
    `export const DR_TITLES: readonly string[] = [\n` +
    names.map(n => `  ${JSON.stringify(n)},`).join('\n') +
    `\n]\n`
  fs.writeFileSync(OUT, body)
  console.log(`wrote ${names.length} titles → ${path.relative(process.cwd(), OUT)}`)
}

main().catch(e => { console.error(e); process.exit(1) })
